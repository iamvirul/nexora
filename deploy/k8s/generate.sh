#!/usr/bin/env bash
# Regenerates nexora.yaml from the Helm chart, so the plain manifests never drift from it.
# CI runs this and fails when the committed file differs: rerun it after changing the chart.
#
#   deploy/k8s/generate.sh
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
chart="$here/../helm/nexora"
out="$here/nexora.yaml"

{
  echo "# Generated by deploy/k8s/generate.sh from deploy/helm/nexora. Do not edit by hand."
  echo "# Defaults: namespace nexora, embedded H2 on a 1Gi PersistentVolumeClaim, API key from"
  echo "# Secret nexora-api-key (key api-key). See deploy/k8s/README.md."
  helm template nexora "$chart" --namespace nexora
} > "$out"

echo "wrote $out"
